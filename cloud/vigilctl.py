def cmd_edit_camera(a):
    st = load()
    c = next((c for c in st["cameras"] if c["id"] == a.camera), None)
    if not c:
        sys.exit("No camera %s" % a.camera)
    for k in ("name", "home", "room", "tz", "pull_url", "floor_alert_s"):
        v = getattr(a, k)
        if v is not None:
            c[k] = v
    if a.hospital is not None:
        c["bed_exit_always"] = a.hospital == "on"
    if a.face is not None:
        c["face_id"] = a.face == "on"
    save(st)
    render(st)
    compose_up(st)
    print("Updated %s." % a.camera)


def cmd_remove_camera(a):
    st = load()
    for c in st["cameras"]:
        if c["id"] == a.camera:
            c["removed"] = True
    save(st)
    render(st)
    compose_up(st)
    print("Stopped %s. Its data stays in data/sites/%s until you delete it." % (a.camera, a.camera))


def cmd_add_user(a):
    from werkzeug.security import generate_password_hash
    pw = a.password or secrets.token_urlsafe(9)
    c = gw_db()
    c.execute("INSERT INTO users (email, name, pw_hash, is_admin) VALUES (?,?,?,?)",
              (a.email.strip().lower(), a.name, generate_password_hash(pw), 1 if a.admin else 0))
    if "email_verified" in {r[1] for r in c.execute("PRAGMA table_info(users)")}:
        c.execute("UPDATE users SET email_verified=1 WHERE email=?", (a.email.strip().lower(),))   # added by hand: trusted
    c.commit()
    print("Account created: %s   password: %s   (they can change it in the app)" % (a.email, pw))


def cmd_reset_password(a):
    from werkzeug.security import generate_password_hash
    pw = secrets.token_urlsafe(9)
    c = gw_db()
    n = c.execute("UPDATE users SET pw_hash=? WHERE email=?", (generate_password_hash(pw),
                                                               a.email.strip().lower())).rowcount
    c.execute("DELETE FROM tokens WHERE user_id=(SELECT id FROM users WHERE email=?)", (a.email.strip().lower(),))
    c.commit()
    print("New password for %s: %s" % (a.email, pw) if n else "No such account")


def cmd_grant(a):
    st = load()
    if not any(c["id"] == a.camera for c in st["cameras"]):
        sys.exit("No camera %s" % a.camera)
    c = gw_db()
    u = c.execute("SELECT id FROM users WHERE email=?", (a.email.strip().lower(),)).fetchone()
    if not u:
        sys.exit("No account %s (add-user first)" % a.email)
    if a.revoke:
        c.execute("DELETE FROM grants WHERE user_id=? AND site_id=?", (u[0], a.camera))
    else:
        c.execute("INSERT OR REPLACE INTO grants VALUES (?,?,?)", (u[0], a.camera, a.role))
    c.commit()
    print(("Removed" if a.revoke else "Granted") + " %s -> %s" % (a.email, a.camera))


def cmd_users(_a):
    c = gw_db()
    for r in c.execute("SELECT u.email, u.name, u.is_admin, GROUP_CONCAT(g.site_id) FROM users u "
                       "LEFT JOIN grants g ON g.user_id=u.id GROUP BY u.id"):
        print("%-34s %-18s %-6s %s" % (r[0], r[1] or "", "admin" if r[2] else "", r[3] or ""))


def cmd_apply(_a):
    st = load()
    render(st)
    compose_up(st)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("init"); s.add_argument("--domain", required=True); s.add_argument("--cpus", type=float, default=2)
    s.set_defaults(f=cmd_init)
    s = sub.add_parser("add-camera"); s.add_argument("--name", required=True); s.add_argument("--home")
    s.add_argument("--room"); s.add_argument("--tz", default="UTC"); s.add_argument("--id")
    s.add_argument("--pull-url", help="RTSP address the cloud can reach, for cameras that cannot push")
    s.add_argument("--hospital", action="store_true", help="patient bed: bed-exit alerts at any hour, not just at night")
    s.add_argument("--floor-alert-s", type=int, default=60, help="alert after this long on the floor (0 = off)")
    s.add_argument("--no-face", action="store_true", dest="no_face",
                   help="do not use face matching to tell people apart on this camera")
    s.set_defaults(f=cmd_add_camera)
    sub.add_parser("cameras").set_defaults(f=cmd_cameras)
    s = sub.add_parser("camera-url"); s.add_argument("camera"); s.set_defaults(f=cmd_camera_url)
    s = sub.add_parser("card"); s.add_argument("camera"); s.add_argument("--tapo-user"); s.add_argument("--tapo-pass")
    s.add_argument("--app-link", help="where to get the app, e.g. the TestFlight link"); s.add_argument("--contact", dest="help",
        help="who to contact, e.g. an email address"); s.set_defaults(f=cmd_card)
    s = sub.add_parser("edit-camera"); s.add_argument("camera"); s.add_argument("--name"); s.add_argument("--home")
    s.add_argument("--room"); s.add_argument("--tz"); s.add_argument("--pull-url", dest="pull_url")
    s.add_argument("--floor-alert-s", type=int, dest="floor_alert_s"); s.add_argument("--hospital", choices=["on", "off"])
    s.add_argument("--face", choices=["on", "off"], help="face matching on this camera")
    s.set_defaults(f=cmd_edit_camera)
    s = sub.add_parser("remove-camera"); s.add_argument("camera"); s.set_defaults(f=cmd_remove_camera)
    s = sub.add_parser("add-user"); s.add_argument("--email", required=True); s.add_argument("--name", default="")
    s.add_argument("--password"); s.add_argument("--admin", action="store_true"); s.set_defaults(f=cmd_add_user)
    s = sub.add_parser("reset-password"); s.add_argument("--email", required=True); s.set_defaults(f=cmd_reset_password)
    s = sub.add_parser("grant"); s.add_argument("--email", required=True); s.add_argument("--camera", required=True)
    s.add_argument("--role", default="caregiver"); s.add_argument("--revoke", action="store_true")
    s.set_defaults(f=cmd_grant)
    sub.add_parser("users").set_defaults(f=cmd_users)
    sub.add_parser("apply").set_defaults(f=cmd_apply)
    a = p.parse_args()
    a.f(a)


if __name__ == "__main__":
    main()
