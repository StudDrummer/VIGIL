#!/usr/bin/env python3
"""
vigilctl: manage the VIGIL cloud (cameras, people's accounts, who sees what).

Run on the cloud server, from the cloud/ folder:

  python3 vigilctl.py init --domain api.vigilhealth.me
  python3 vigilctl.py add-camera --name "Rushil home - living room" --home "Rushil home" --tz America/Los_Angeles
  python3 vigilctl.py cameras
  python3 vigilctl.py camera-url home01           # what to paste into the camera
  python3 vigilctl.py add-user --email mom@example.com --name "Mom"
  python3 vigilctl.py grant --email mom@example.com --camera home01
  python3 vigilctl.py reset-password --email mom@example.com
  python3 vigilctl.py remove-camera home01        # stops it; its data folder is kept
  python3 vigilctl.py apply                       # rewrite configs and (re)start everything

Every change rewrites three generated files and applies them:
  config/sites.json      what the gateway knows about each camera
  config/mediamtx.yml    which camera may send video to which path
  docker-compose.yml     one container per camera, plus the shared services
"""
import argparse
import json
import os
import re
import secrets
import sqlite3
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CONF = os.path.join(HERE, "config")
STATE = os.path.join(CONF, "vigil_cloud.json")      # the source of truth (secret: keep private)
DATA = os.path.join(HERE, "data")


def load():
    if not os.path.exists(STATE):
        sys.exit("Not initialised. Run: python3 vigilctl.py init --domain <your domain>")
    with open(STATE) as f:
        return json.load(f)


def save(st):
    os.makedirs(CONF, exist_ok=True)
    tmp = STATE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(st, f, indent=2)
    os.chmod(tmp, 0o600)
    os.replace(tmp, STATE)


def render(st):
    """Write the three generated files from the state."""
    cams = [c for c in st["cameras"] if not c.get("removed")]
    # gateway
    sites = [{"id": c["id"], "name": c["name"], "home": c.get("home", ""), "room": c.get("room", ""),
              "timezone": c.get("tz", ""), "ntfy_topic": c["ntfy_topic"], "api_key": c["api_key"],
              "internal_url": "http://site-%s:5001" % c["id"]} for c in cams]
    _write(os.path.join(CONF, "sites.json"), json.dumps({"sites": sites}, indent=2), secret=True)

    # mediamtx: each camera may publish only to its own path; sites may only read.
    users = ["  - user: %s\n    pass: %s\n    ips: []\n    permissions:\n      - action: publish\n        path: %s\n"
             % (c["stream_user"], c["stream_pass"], c["id"]) for c in cams]
    users.append("  - user: reader\n    pass: %s\n    ips: []\n    permissions:\n      - action: read\n"
                 % st["reader_pass"])
    paths = []
    for c in cams:
        if c.get("pull_url"):
            paths.append("  %s:\n    source: %s\n    sourceOnDemand: no\n" % (c["id"], c["pull_url"]))
        else:
            paths.append("  %s: {}\n" % c["id"])
    mtx = ("# Generated by vigilctl.py. Do not edit by hand.\n"
           "logLevel: info\n"
           "authMethod: internal\n"
           "authInternalUsers:\n" + "".join(users) +
           "rtmp: yes\nrtmpAddress: :1935\n"
           "rtsp: yes\nrtspAddress: :8554\nrtspTransports: [tcp]\n"
           "hls: no\nwebrtc: no\nsrt: no\napi: no\nmetrics: no\nplayback: no\n"
           "pathDefaults:\n  record: no\n"
           "paths:\n" + ("".join(paths) if paths else "  {}\n"))
    _write(os.path.join(CONF, "mediamtx.yml"), mtx, secret=True)

    # docker compose
    svc = []
    for c in cams:
        svc.append("""
  site-{id}:
    image: vigil-site:latest
    restart: unless-stopped
    environment:
      VIGIL_API_KEY: "{api_key}"
      VIGIL_RTSP_URL: "rtsp://reader:{reader}@mediamtx:8554/{id}"
      VIGIL_ROOM_ID: "room_1"
      VIGIL_NTFY_TOPIC: "{topic}"
      VIGIL_PUSH_LABEL: "{label}"
      VIGIL_LOCAL_WATCHDOG: "0"
      VIGIL_BED_EXIT_ALWAYS: "{bed_always}"
      VIGIL_FLOOR_ALERT_S: "{floor_s}"
      TZ: "{tz}"
      HOME: /root
    volumes:
      - ./data/sites/{id}:/root/passive-health-moniter
    shm_size: "256m"
    cpus: {cpus}
    mem_limit: 3g
    depends_on: [mediamtx]
    networks: [vigil]
""".format(id=c["id"], api_key=c["api_key"], reader=st["reader_pass"], topic=c["ntfy_topic"],
           tz=c.get("tz") or "UTC", cpus=st.get("cpus_per_camera", 2),
           label=(c.get("room") or "").replace('"', ''), bed_always="1" if c.get("bed_exit_always") else "0",
           floor_s=int(c.get("floor_alert_s", 60))))
    compose = """# Generated by vigilctl.py. Do not edit by hand.
services:
  caddy:
    image: caddy:2
    restart: unless-stopped
    ports: ["80:80", "443:443"]
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./data/caddy:/data
    networks: [vigil]

  gateway:
    build: ./gateway
    image: vigil-gateway:latest
    restart: unless-stopped
    environment:
      VIGIL_CONFIG: /config
      VIGIL_DATA: /data
    volumes:
      - ./config:/config:ro
      - ./data/gateway:/data
    networks: [vigil]

  mediamtx:
    image: bluenviron/mediamtx:1
    restart: unless-stopped
    ports: ["1935:1935"]
    volumes:
      - ./config/mediamtx.yml:/mediamtx.yml:ro
    networks: [vigil]
""" + "".join(svc) + """
networks:
  vigil: {}
"""
    _write(os.path.join(HERE, "docker-compose.yml"), compose, secret=True)
    _write(os.path.join(HERE, "Caddyfile"),
           "%s {\n  encode gzip\n  reverse_proxy gateway:8080 {\n    flush_interval -1\n  }\n}\n" % st["domain"])
    for c in cams:
        os.makedirs(os.path.join(DATA, "sites", c["id"]), exist_ok=True)


def _write(path, text, secret=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    if secret:
        os.chmod(path, 0o600)


def compose_up(st, quiet=False):
    if os.environ.get("VIGILCTL_NO_DOCKER") == "1":
        return
    cmd = ["docker", "compose", "up", "-d", "--remove-orphans"]
    if not quiet:
        print("$ " + " ".join(cmd))
    subprocess.run(cmd, cwd=HERE, check=False)


def gw_db():
    os.makedirs(os.path.join(DATA, "gateway"), exist_ok=True)
    path = os.path.join(DATA, "gateway", "gateway.db")
    sys.path.insert(0, os.path.join(HERE, "gateway"))
    os.environ.setdefault("VIGIL_WATCHDOG", "0")
    os.environ["VIGIL_DATA"] = os.path.join(DATA, "gateway")
    os.environ["VIGIL_CONFIG"] = CONF
    import gateway  # noqa: F401  creates the tables
    return sqlite3.connect(path)


def camera_url(st, c):
    return "rtmp://%s:1935/%s?user=%s&pass=%s" % (st["domain"], c["id"], c["stream_user"], c["stream_pass"])


# ---------------------------------------------------------------- commands
def cmd_init(a):
    if os.path.exists(STATE):
        sys.exit("Already initialised (%s)." % STATE)
    st = {"domain": a.domain, "reader_pass": secrets.token_urlsafe(18), "cameras": [],
          "cpus_per_camera": a.cpus}
    save(st)
    render(st)
    print("Initialised for %s. Next: point a DNS A record for %s at this server's IP, then add a camera."
          % (a.domain, a.domain))


def cmd_add_camera(a):
    st = load()
    n = len(st["cameras"]) + 1
    cid = a.id or "home%02d" % n
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,30}", cid) or any(c["id"] == cid for c in st["cameras"]):
        sys.exit("Camera id must be new, lowercase letters/digits/dashes: %s" % cid)
    c = {"id": cid, "name": a.name, "home": a.home or a.name, "room": a.room or "", "tz": a.tz,
         "api_key": secrets.token_urlsafe(32), "stream_user": "cam_" + cid.replace("-", "_"),
         "stream_pass": secrets.token_urlsafe(18), "ntfy_topic": "vigil-" + secrets.token_hex(12),
         "pull_url": a.pull_url or "", "bed_exit_always": bool(a.hospital), "floor_alert_s": a.floor_alert_s}
    st["cameras"].append(c)
    save(st)
    render(st)
    compose_up(st)
    print("\nCamera '%s' added as %s." % (a.name, cid))
    if c["pull_url"]:
        print("The cloud will pull its video from the address you gave.")
    else:
        print("In the camera's settings (Network > RTMP > Custom address), enter:\n  %s" % camera_url(st, c))
    print("Caregivers get alerts by subscribing to this topic in the ntfy app:\n  %s" % c["ntfy_topic"])


def cmd_cameras(_a):
    st = load()
    for c in st["cameras"]:
        print("%-10s %-38s %-26s %s%s" % (c["id"], c["name"], c.get("home", ""), c.get("tz", ""),
                                         "  (removed)" if c.get("removed") else ""))


def cmd_camera_url(a):
    st = load()
    c = next((c for c in st["cameras"] if c["id"] == a.camera), None)
    if not c:
        sys.exit("No camera %s" % a.camera)
    print(camera_url(st, c))
    print("ntfy topic: %s" % c["ntfy_topic"])


def cmd_edit_camera(a):
    st = load()
    c = next((c for c in st["cameras"] if c["id"] == a.camera), None)
    if not c:
        sys.exit("No camera %s" % a.camera)
    for k in ("name", "home", "room", "tz", "pull_url", "floor_alert_s"):
        v = getattr(a, k)
        if v is not None:
            c[k] = v
    if a.hospital is not None:
        c["bed_exit_always"] = a.hospital == "on"
    save(st)
    render(st)
    compose_up(st)
    print("Updated %s." % a.camera)


def cmd_remove_camera(a):
    st = load()
    for c in st["cameras"]:
        if c["id"] == a.camera:
            c["removed"] = True
    save(st)
    render(st)
    compose_up(st)
    print("Stopped %s. Its data stays in data/sites/%s until you delete it." % (a.camera, a.camera))


def cmd_add_user(a):
    from werkzeug.security import generate_password_hash
    pw = a.password or secrets.token_urlsafe(9)
    c = gw_db()
    c.execute("INSERT INTO users (email, name, pw_hash, is_admin) VALUES (?,?,?,?)",
              (a.email.strip().lower(), a.name, generate_password_hash(pw), 1 if a.admin else 0))
    c.commit()
    print("Account created: %s   password: %s   (they can change it in the app)" % (a.email, pw))


def cmd_reset_password(a):
    from werkzeug.security import generate_password_hash
    pw = secrets.token_urlsafe(9)
    c = gw_db()
    n = c.execute("UPDATE users SET pw_hash=? WHERE email=?", (generate_password_hash(pw),
                                                               a.email.strip().lower())).rowcount
    c.execute("DELETE FROM tokens WHERE user_id=(SELECT id FROM users WHERE email=?)", (a.email.strip().lower(),))
    c.commit()
    print("New password for %s: %s" % (a.email, pw) if n else "No such account")


def cmd_grant(a):
    st = load()
    if not any(c["id"] == a.camera for c in st["cameras"]):
        sys.exit("No camera %s" % a.camera)
    c = gw_db()
    u = c.execute("SELECT id FROM users WHERE email=?", (a.email.strip().lower(),)).fetchone()
    if not u:
        sys.exit("No account %s (add-user first)" % a.email)
    if a.revoke:
        c.execute("DELETE FROM grants WHERE user_id=? AND site_id=?", (u[0], a.camera))
    else:
        c.execute("INSERT OR REPLACE INTO grants VALUES (?,?,?)", (u[0], a.camera, a.role))
    c.commit()
    print(("Removed" if a.revoke else "Granted") + " %s -> %s" % (a.email, a.camera))


def cmd_users(_a):
    c = gw_db()
    for r in c.execute("SELECT u.email, u.name, u.is_admin, GROUP_CONCAT(g.site_id) FROM users u "
                       "LEFT JOIN grants g ON g.user_id=u.id GROUP BY u.id"):
        print("%-34s %-18s %-6s %s" % (r[0], r[1] or "", "admin" if r[2] else "", r[3] or ""))


def cmd_apply(_a):
    st = load()
    render(st)
    compose_up(st)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("init"); s.add_argument("--domain", required=True); s.add_argument("--cpus", type=float, default=2)
    s.set_defaults(f=cmd_init)
    s = sub.add_parser("add-camera"); s.add_argument("--name", required=True); s.add_argument("--home")
    s.add_argument("--room"); s.add_argument("--tz", default="UTC"); s.add_argument("--id")
    s.add_argument("--pull-url", help="RTSP address the cloud can reach, for cameras that cannot push")
    s.add_argument("--hospital", action="store_true", help="patient bed: bed-exit alerts at any hour, not just at night")
    s.add_argument("--floor-alert-s", type=int, default=60, help="alert after this long on the floor (0 = off)")
    s.set_defaults(f=cmd_add_camera)
    sub.add_parser("cameras").set_defaults(f=cmd_cameras)
    s = sub.add_parser("camera-url"); s.add_argument("camera"); s.set_defaults(f=cmd_camera_url)
    s = sub.add_parser("edit-camera"); s.add_argument("camera"); s.add_argument("--name"); s.add_argument("--home")
    s.add_argument("--room"); s.add_argument("--tz"); s.add_argument("--pull-url", dest="pull_url")
    s.add_argument("--floor-alert-s", type=int, dest="floor_alert_s"); s.add_argument("--hospital", choices=["on", "off"])
    s.set_defaults(f=cmd_edit_camera)
    s = sub.add_parser("remove-camera"); s.add_argument("camera"); s.set_defaults(f=cmd_remove_camera)
    s = sub.add_parser("add-user"); s.add_argument("--email", required=True); s.add_argument("--name", default="")
    s.add_argument("--password"); s.add_argument("--admin", action="store_true"); s.set_defaults(f=cmd_add_user)
    s = sub.add_parser("reset-password"); s.add_argument("--email", required=True); s.set_defaults(f=cmd_reset_password)
    s = sub.add_parser("grant"); s.add_argument("--email", required=True); s.add_argument("--camera", required=True)
    s.add_argument("--role", default="caregiver"); s.add_argument("--revoke", action="store_true")
    s.set_defaults(f=cmd_grant)
    sub.add_parser("users").set_defaults(f=cmd_users)
    sub.add_parser("apply").set_defaults(f=cmd_apply)
    a = p.parse_args()
    a.f(a)


if __name__ == "__main__":
    main()
