#!/usr/bin/env python3
"""
vigilctl: manage the VIGIL cloud (cameras, people's accounts, who sees what).

Run on the cloud server, from the cloud/ folder:

  python3 vigilctl.py init --domain api.vigilhealth.me
  python3 vigilctl.py add-camera --name "Rushil home - living room" --home "Rushil home" --tz America/Los_Angeles
  python3 vigilctl.py cameras
  python3 vigilctl.py camera-url home01           # setup code and relay settings again
  python3 vigilctl.py card home01 --tapo-user vigil --tapo-pass ... --app-link ... --contact ...   # printable card
  python3 vigilctl.py add-user --email mom@example.com --name "Mom"
  python3 vigilctl.py grant --email mom@example.com --camera home01
  python3 vigilctl.py reset-password --email mom@example.com
  python3 vigilctl.py remove-camera home01        # stops it; its data folder is kept
  python3 vigilctl.py apply                       # rewrite configs and (re)start everything

Every change rewrites three generated files and applies them:
  config/sites.json      what the gateway knows about each camera
  config/mediamtx.yml    which camera may send video to which path
  docker-compose.yml     one container per camera, plus the shared services
"""
import argparse
import json
import os
import re
import secrets
import sqlite3
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CONF = os.path.join(HERE, "config")
STATE = os.path.join(CONF, "vigil_cloud.json")      # the source of truth (secret: keep private)
DATA = os.path.join(HERE, "data")


def load():
    if not os.path.exists(STATE):
        sys.exit("Not initialised. Run: python3 vigilctl.py init --domain <your domain>")
    with open(STATE) as f:
        return json.load(f)


def save(st):
    os.makedirs(CONF, exist_ok=True)
    tmp = STATE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(st, f, indent=2)
    os.chmod(tmp, 0o600)
    os.replace(tmp, STATE)


CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"     # no 0/O or 1/I mix-ups


def new_setup_code(st):
    used = {c.get("setup_code") for c in st.get("cameras", [])}
    while True:
        raw = "".join(secrets.choice(CODE_ALPHABET) for _ in range(8))
        code = raw[:4] + "-" + raw[4:]
        if code not in used:
            return code


def migrate(st):
    """Older cameras get a setup code and an SRT passphrase."""
    changed = False
    for c in st.get("cameras", []):
        if not c.get("setup_code"):
            c["setup_code"] = new_setup_code(st); changed = True
        if not c.get("srt_passphrase"):
            c["srt_passphrase"] = secrets.token_hex(16); changed = True
    return changed


def render(st):
    """Write the three generated files from the state."""
    if migrate(st):
        save(st)
    cams = [c for c in st["cameras"] if not c.get("removed")]
    # gateway
    sites = [{"id": c["id"], "name": c["name"], "home": c.get("home", ""), "room": c.get("room", ""),
              "timezone": c.get("tz", ""), "ntfy_topic": c["ntfy_topic"], "api_key": c["api_key"],
              "setup_code": c.get("setup_code", ""),
              "internal_url": "http://site-%s:5001" % c["id"]} for c in cams]
    _write(os.path.join(CONF, "sites.json"), json.dumps({"sites": sites}, indent=2), secret=True)

    # mediamtx: each camera may publish only to its own path; sites may only read.
    users = ["  - user: %s\n    pass: %s\n    ips: []\n    permissions:\n      - action: publish\n        path: %s\n"
             % (c["stream_user"], c["stream_pass"], c["id"]) for c in cams]
    users.append("  - user: reader\n    pass: %s\n    ips: []\n    permissions:\n      - action: read\n"
                 % st["reader_pass"])
    paths = []
    for c in cams:
        if c.get("pull_url"):
            paths.append("  %s:\n    source: %s\n    sourceOnDemand: no\n" % (c["id"], c["pull_url"]))
        else:
            # SRT_V1: video from a VIGIL relay box arrives encrypted with this camera's own passphrase.
            paths.append("  %s:\n    srtPublishPassphrase: %s\n" % (c["id"], c["srt_passphrase"]))
    mtx = ("# Generated by vigilctl.py. Do not edit by hand.\n"
           "logLevel: info\n"
           "authMethod: internal\n"
           "authInternalUsers:\n" + "".join(users) +
           "rtmp: yes\nrtmpAddress: :1935\n"
           "rtsp: yes\nrtspAddress: :8554\nrtspTransports: [tcp]\n"
           "srt: yes\nsrtAddress: :8890\n"
           "hls: no\nwebrtc: no\napi: no\nmetrics: no\nplayback: no\n"
           "pathDefaults:\n  record: no\n"
           "paths:\n" + ("".join(paths) if paths else "  {}\n"))
    _write(os.path.join(CONF, "mediamtx.yml"), mtx, secret=True)

    # docker compose
    svc = []
    for c in cams:
        svc.append("""
  site-{id}:
    image: vigil-site:latest
    restart: unless-stopped
    environment:
      VIGIL_API_KEY: "{api_key}"
      VIGIL_RTSP_URL: "rtsp://reader:{reader}@mediamtx:8554/{id}"
      VIGIL_ROOM_ID: "room_1"
      VIGIL_NTFY_TOPIC: "{topic}"
      VIGIL_PUSH_LABEL: "{label}"
      VIGIL_LOCAL_WATCHDOG: "0"
      VIGIL_BED_EXIT_ALWAYS: "{bed_always}"
      VIGIL_FLOOR_ALERT_S: "{floor_s}"
      TZ: "{tz}"
      HOME: /root
    volumes:
      - ./data/sites/{id}:/root/passive-health-moniter
    shm_size: "256m"
    cpus: {cpus}
    mem_limit: 3g
    depends_on: [mediamtx]
    networks: [vigil]
""".format(id=c["id"], api_key=c["api_key"], reader=st["reader_pass"], topic=c["ntfy_topic"],
           tz=c.get("tz") or "UTC", cpus=st.get("cpus_per_camera", 2),
           label=(c.get("room") or "").replace('"', ''), bed_always="1" if c.get("bed_exit_always") else "0",
           floor_s=int(c.get("floor_alert_s", 60))))
    compose = """# Generated by vigilctl.py. Do not edit by hand.
services:
  caddy:
    image: caddy:2
    restart: unless-stopped
    ports: ["80:80", "443:443"]
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./data/caddy:/data
    networks: [vigil]

  gateway:
    build: ./gateway
    image: vigil-gateway:latest
    restart: unless-stopped
    environment:
      VIGIL_CONFIG: /config
      VIGIL_DATA: /data
    env_file:
      - ./config/email.env
    volumes:
      - ./config:/config:ro
      - ./data/gateway:/data
    networks: [vigil]

  mediamtx:
    image: bluenviron/mediamtx:1
    restart: unless-stopped
    ports: ["1935:1935", "8890:8890/udp"]
    volumes:
      - ./config/mediamtx.yml:/mediamtx.yml:ro
    networks: [vigil]
""" + "".join(svc) + """
networks:
  vigil: {}
"""
    _write(os.path.join(HERE, "docker-compose.yml"), compose, secret=True)
    _write(os.path.join(HERE, "Caddyfile"),
           "%s {\n  encode gzip\n  reverse_proxy gateway:8080 {\n    flush_interval -1\n  }\n}\n" % st["domain"])
    for c in cams:
        os.makedirs(os.path.join(DATA, "sites", c["id"]), exist_ok=True)
    ep = os.path.join(CONF, "email.env")
    if not os.path.exists(ep):
        _write(ep, "# ALERT_EMAIL_V1: fill these in to send alert, welcome and password emails.\n"
                   "# Example for Google Workspace / Gmail with an app password:\n"
                   "#   VIGIL_SMTP_HOST=smtp.gmail.com\n#   VIGIL_SMTP_PORT=587\n"
                   "VIGIL_SMTP_HOST=\nVIGIL_SMTP_PORT=587\nVIGIL_SMTP_USER=\nVIGIL_SMTP_PASSWORD=\n"
                   "VIGIL_SMTP_FROM=VIGIL <alerts@vigilhealth.me>\n", secret=True)


def _write(path, text, secret=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    if secret:
        os.chmod(path, 0o600)


def compose_up(st, quiet=False):
    if os.environ.get("VIGILCTL_NO_DOCKER") == "1":
        return
    cmd = ["docker", "compose", "up", "-d", "--remove-orphans"]
    if not quiet:
        print("$ " + " ".join(cmd))
    subprocess.run(cmd, cwd=HERE, check=False)


def gw_db():
    os.makedirs(os.path.join(DATA, "gateway"), exist_ok=True)
    path = os.path.join(DATA, "gateway", "gateway.db")
    sys.path.insert(0, os.path.join(HERE, "gateway"))
    os.environ.setdefault("VIGIL_WATCHDOG", "0")
    os.environ["VIGIL_DATA"] = os.path.join(DATA, "gateway")
    os.environ["VIGIL_CONFIG"] = CONF
    import gateway  # noqa: F401  creates the tables
    return sqlite3.connect(path)


def relay_config(st, c):
    """SRT_V1: the settings file for this camera's VIGIL relay box."""
    return ("# VIGIL relay settings for camera %s (%s). Keep private.\n"
            "VIGIL_CAMERA_ID=%s\nVIGIL_CLOUD_HOST=%s\nVIGIL_SRT_PORT=8890\n"
            "VIGIL_STREAM_USER=%s\nVIGIL_STREAM_PASS=%s\nVIGIL_SRT_PASSPHRASE=%s\n"
            "VIGIL_RTMP_FALLBACK=%s\n" % (c["id"], c["name"], c["id"], st["domain"], c["stream_user"],
                                           c["stream_pass"], c["srt_passphrase"], camera_url(st, c)))


def camera_url(st, c):
    return "rtmp://%s:1935/%s?user=%s&pass=%s" % (st["domain"], c["id"], c["stream_user"], c["stream_pass"])


# ---------------------------------------------------------------- commands
def cmd_init(a):
    if os.path.exists(STATE):
        sys.exit("Already initialised (%s)." % STATE)
    st = {"domain": a.domain, "reader_pass": secrets.token_urlsafe(18), "cameras": [],
          "cpus_per_camera": a.cpus}
    save(st)
    render(st)
    print("Initialised for %s. Next: point a DNS A record for %s at this server's IP, then add a camera."
          % (a.domain, a.domain))


def cmd_add_camera(a):
    st = load()
    n = len(st["cameras"]) + 1
    cid = a.id or "home%02d" % n
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,30}", cid) or any(c["id"] == cid for c in st["cameras"]):
        sys.exit("Camera id must be new, lowercase letters/digits/dashes: %s" % cid)
    c = {"id": cid, "name": a.name, "home": a.home or a.name, "room": a.room or "", "tz": a.tz,
         "api_key": secrets.token_urlsafe(32), "stream_user": "cam_" + cid.replace("-", "_"),
         "stream_pass": secrets.token_urlsafe(18), "ntfy_topic": "vigil-" + secrets.token_hex(12),
         "setup_code": new_setup_code(st), "srt_passphrase": secrets.token_hex(16),
         "pull_url": a.pull_url or "", "bed_exit_always": bool(a.hospital), "floor_alert_s": a.floor_alert_s}
    st["cameras"].append(c)
    save(st)
    render(st)
    compose_up(st)
    rp = os.path.join(CONF, "relay_%s.env" % cid)
    _write(rp, relay_config(st, c), secret=True)
    print("\nCamera '%s' added as %s." % (a.name, cid))
    print("SETUP CODE (print on the card; the family types it in the app):  %s" % c["setup_code"])
    print("Relay box settings file: %s" % rp)
    if c["pull_url"]:
        print("The cloud will pull its video from the address you gave.")
    else:
        print("With a VIGIL relay box: copy the settings file above onto it and run relay/install.sh.")
        print("A camera that can send RTMP by itself instead: Network > RTMP > Custom address:\n  %s" % camera_url(st, c))
    print("Caregivers get alerts by subscribing to this topic in the ntfy app:\n  %s" % c["ntfy_topic"])


